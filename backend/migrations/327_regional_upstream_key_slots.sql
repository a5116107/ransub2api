-- Upstream credentials have their own immutable registry and quota namespace.
-- No account/downstream-key ID or truncated hash represents an upstream key.
CREATE TABLE IF NOT EXISTS regional_upstream_keys (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
 fingerprint TEXT NOT NULL UNIQUE CHECK (fingerprint ~ '^[0-9a-f]{64}$')
);
CREATE TABLE IF NOT EXISTS regional_upstream_key_policy (
 singleton BOOLEAN PRIMARY KEY DEFAULT true CHECK (singleton),
 revision BIGINT NOT NULL CHECK (revision >= 0 AND revision <= 9007199254740991),
 digest TEXT NOT NULL CHECK (digest ~ '^[0-9a-f]{64}$'),
 limits JSONB NOT NULL CHECK (jsonb_typeof(limits) = 'object')
);
CREATE TABLE IF NOT EXISTS regional_upstream_key_policy_cache (
 region_id TEXT PRIMARY KEY,
 revision BIGINT NOT NULL CHECK (revision >= 0),
 digest TEXT NOT NULL CHECK (digest ~ '^[0-9a-f]{64}$'),
 issued_at TIMESTAMPTZ NOT NULL,
 expires_at TIMESTAMPTZ NOT NULL CHECK (expires_at > issued_at),
 payload JSONB NOT NULL
);
ALTER TABLE regional_slot_budgets DROP CONSTRAINT IF EXISTS regional_slot_budgets_kind_check;
ALTER TABLE regional_slot_budgets ADD CONSTRAINT regional_slot_budgets_kind_check
 CHECK (kind IN ('account','user','api_key','upstream_key'));
